"""Deriv synthetic indices over the official WebSocket API (developers.deriv.com).

Deriv states these instruments are generated by a cryptographically secure random
number generator. The spec expects most pattern modules to fail the symbol gate
here, and the honest output is often "no setup". This adapter only fetches data.

Requests used (JSON over WebSocket, one request per req_id):
  {"active_symbols": "brief", "product_type": "basic"}         -> symbols + pip sizes
  {"ticks_history": "R_75", "end": "latest", "count": N,
   "style": "candles", "granularity": 900, "adjust_start_time": 1}
  {"ticks": "R_75", "subscribe": 1}                            -> live ticks

The endpoint URL is configurable (DERIV_WS_URL); the default is the documented
public websocket host with the app id appended as a query parameter.
"""
from __future__ import annotations

import asyncio
import json
import logging
import time
from datetime import datetime, timedelta, timezone
from typing import Any, AsyncIterator

import websockets

from engine.data.base import DataAdapter, DataAdapterError
from engine.data.discovery import deriv_market_class, symbols_from_deriv_rows
from engine.models import (
    Candle,
    InstrumentMetadata,
    MarketClass,
    SymbolInfo,
    Tick,
    Timeframe,
    utcnow,
)

log = logging.getLogger(__name__)

# Verified live 2026-10-12: wss://ws.derivws.com/websockets/v3 (and ws.binaryws.com) return
# Cloudflare HTTP 520 from this network, while the current public endpoint below serves
# real candles. app_id is optional on the public endpoint but recommended.
DEFAULT_WS_URL = "wss://api.derivws.com/trading/v1/options/ws/public"

_GRANULARITY: dict[Timeframe, int] = {
    Timeframe.M1: 60, Timeframe.M5: 300, Timeframe.M15: 900, Timeframe.M30: 1800,
    Timeframe.H1: 3600, Timeframe.H2: 7200, Timeframe.H4: 14400, Timeframe.H8: 28800,
    Timeframe.D1: 86400,
}


class DerivTransportError(DataAdapterError):
    """Connection-level failure (reset, timeout, DNS). Worth retrying; an API error is not."""


class DerivAdapter(DataAdapter):
    name = "deriv"

    def __init__(
        self,
        app_id: str = "",
        ws_url: str = DEFAULT_WS_URL,
        *,
        timeout: float = 20.0,
        symbol_ttl: float = 600.0,
    ) -> None:
        self.app_id = app_id
        self.url = f"{ws_url}?app_id={app_id}" if app_id else ws_url
        self.timeout = timeout
        self._req_id = 0
        # canonical id -> Deriv's own symbol (frxGBPUSD for GBPUSD). The symbol
        # list is a websocket round trip, so it is cached rather than fetched per call.
        self.symbol_ttl = symbol_ttl
        self._symbol_index: dict[str, str] | None = None
        self._symbol_index_at: float = 0.0

    # ------------------------------------------------------------------ infra

    def _next_id(self) -> int:
        self._req_id += 1
        return self._req_id

    async def _call(self, payload: dict[str, Any], *, attempts: int = 3) -> dict[str, Any]:
        """One request. Transport failures are retried with backoff because this
        network drops websocket connections; API errors are returned immediately."""
        last: Exception | None = None
        for attempt in range(attempts):
            try:
                return await self._call_once(payload)
            except DerivTransportError as exc:
                last = exc
                log.warning("Deriv transport error (attempt %d/%d): %s", attempt + 1, attempts, exc)
                if attempt + 1 < attempts:
                    await asyncio.sleep(0.75 * (2 ** attempt))
        assert last is not None
        raise last

    async def _call_once(self, payload: dict[str, Any]) -> dict[str, Any]:
        req_id = self._next_id()
        payload = {**payload, "req_id": req_id}
        try:
            async with websockets.connect(self.url, open_timeout=self.timeout, close_timeout=5) as ws:
                await ws.send(json.dumps(payload))
                while True:
                    raw = await asyncio.wait_for(ws.recv(), timeout=self.timeout)
                    msg = json.loads(raw)
                    if msg.get("req_id") != req_id:
                        continue
                    if msg.get("error"):
                        err = msg["error"]
                        raise DataAdapterError(f"Deriv error {err.get('code')}: {err.get('message')}")
                    return msg
        except (OSError, asyncio.TimeoutError) as exc:
            raise DerivTransportError(f"Deriv websocket call failed: {exc}") from exc

    # ------------------------------------------------------------------ api

    async def _active_symbols(self) -> list[dict[str, Any]]:
        """Symbol list. The current public endpoint returns underlying_symbol /
        underlying_symbol_name / pip_size; older deployments used symbol / display_name /
        pip. Both shapes are accepted so the adapter survives the transition."""
        msg = await self._call({"active_symbols": "brief"})
        return list(msg.get("active_symbols") or [])

    @staticmethod
    def _row_symbol(row: dict[str, Any]) -> str:
        return str(row.get("underlying_symbol") or row.get("symbol") or "")

    @staticmethod
    def _row_display(row: dict[str, Any]) -> str:
        return str(row.get("underlying_symbol_name") or row.get("display_name") or "")

    @staticmethod
    def _row_pip(row: dict[str, Any]) -> float | None:
        raw = row.get("pip_size", row.get("pip"))
        try:
            return float(raw) if raw is not None else None
        except (TypeError, ValueError):
            return None

    async def list_symbols(self) -> list[SymbolInfo]:
        """Every instrument Deriv currently lists, mapped onto our market classes.

        Canonical ids strip Deriv's own prefixes (frxGBPUSD -> GBPUSD, cryBTCUSD ->
        BTCUSD) so one instrument has one id across providers; synthetic indices keep
        Deriv's symbol (R_75, 1HZ100V, stpRNG).
        """
        rows = await self._active_symbols()
        return symbols_from_deriv_rows(rows)

    async def provider_symbol(self, canonical_id: str) -> str:
        """Deriv's own symbol for a canonical id, refreshing the cache on a miss."""
        index = await self._symbol_index_map()
        if canonical_id in index:
            return index[canonical_id]
        self._symbol_index = None  # maybe a newly listed instrument: refetch once
        index = await self._symbol_index_map()
        return index.get(canonical_id, canonical_id)

    async def _symbol_index_map(self) -> dict[str, str]:
        now = time.monotonic()
        if self._symbol_index is None or (now - self._symbol_index_at) > self.symbol_ttl:
            rows = await self._active_symbols()
            self._symbol_index = {
                info.canonical_id: info.provider_symbols.get("deriv", info.canonical_id)
                for info in symbols_from_deriv_rows(rows)
            }
            self._symbol_index_at = now
        return self._symbol_index

    async def get_instrument_metadata(self, canonical_id: str) -> InstrumentMetadata:
        provider = await self.provider_symbol(canonical_id)
        rows = await self._active_symbols()
        row = next((r for r in rows if self._row_symbol(r) == provider), None)
        if row is None:
            raise DataAdapterError(f"Deriv does not list symbol {canonical_id!r}")
        pip = self._row_pip(row)
        market_class = deriv_market_class(row) or MarketClass.SYNTHETIC
        return InstrumentMetadata(
            canonical_id=canonical_id,
            symbol=self._row_display(row) or canonical_id,
            market_class=market_class,
            venue="DERIV",
            quote_currency=str(row.get("quote_currency") or ""),
            base_currency=str(row.get("underlying_symbol") or row.get("symbol") or ""),
            digits=None,
            tick_size=pip,
            contract_size=None,
            min_stop_distance=None,
            typical_spread=None,
            price_grid=None,  # Step index grid: [OPEN] confirm from Deriv contract specs
            trading_hours={"mode": "24/7"},
            value_per_price_unit=None,
            extra={"raw_symbol": {k: v for k, v in row.items()}},
        )

    async def get_candles(
        self,
        canonical_id: str,
        timeframe: Timeframe,
        start: datetime | None = None,
        end: datetime | None = None,
        limit: int | None = None,
        closed_only: bool = True,
    ) -> list[Candle]:
        granularity = _GRANULARITY.get(timeframe)
        if granularity is None:
            raise DataAdapterError(f"Deriv does not support timeframe {timeframe.value}")
        count = int(limit) if limit else 1000
        provider = await self.provider_symbol(canonical_id)
        payload: dict[str, Any] = {
            "ticks_history": provider,
            "adjust_start_time": 1,
            "count": max(1, min(count, 5000)),
            "end": int(end.timestamp()) if end else "latest",
            "style": "candles",
            "granularity": granularity,
        }
        if start is not None:
            payload["start"] = int(start.timestamp())
        msg = await self._call(payload)
        now = utcnow()
        out: list[Candle] = []
        for row in msg.get("candles") or []:
            try:
                open_time = datetime.fromtimestamp(int(row["epoch"]), tz=timezone.utc)
                is_closed = (open_time + timedelta(seconds=granularity)) <= now
                if closed_only and not is_closed:
                    continue
                out.append(
                    Candle(
                        symbol=canonical_id,
                        timeframe=timeframe,
                        open_time=open_time,
                        open=float(row["open"]),
                        high=float(row["high"]),
                        low=float(row["low"]),
                        close=float(row["close"]),
                        tick_volume=None,
                        real_volume=None,
                        is_closed=is_closed,
                        source="deriv",
                    )
                )
            except (KeyError, TypeError, ValueError):
                log.warning("Deriv candle row with unexpected shape skipped: %r", row)
        out.sort(key=lambda c: c.open_time)
        if limit:
            out = out[-int(limit):]
        return out

    async def subscribe(self, canonical_id: str) -> AsyncIterator[Tick]:  # type: ignore[override]
        try:
            provider = await self.provider_symbol(canonical_id)
            async with websockets.connect(self.url, open_timeout=self.timeout) as ws:
                await ws.send(json.dumps({"ticks": provider, "subscribe": 1, "req_id": self._next_id()}))
                while True:
                    raw = await ws.recv()
                    msg = json.loads(raw)
                    if msg.get("error"):
                        err = msg["error"]
                        raise DataAdapterError(f"Deriv error {err.get('code')}: {err.get('message')}")
                    if msg.get("msg_type") != "tick":
                        continue
                    tick = msg.get("tick") or {}
                    yield Tick(
                        symbol=canonical_id,
                        time=datetime.fromtimestamp(int(tick.get("epoch") or 0), tz=timezone.utc),
                        last=float(tick.get("quote")),
                    )
        except (OSError, asyncio.TimeoutError) as exc:
            raise DerivTransportError(f"Deriv tick stream failed: {exc}") from exc